def add(a, b):        # Definiuje funkcję o nazwie 'add', przyjmującą dwa parametry: 'a' i 'b'
    result = a + b     # Dodaje przekazane liczby i zapisuje wynik w zmiennej lokalnej 'result'
    return result      # Zwraca obliczony wynik na zewnątrz funkcji

sum_value = add(5, 3)     # Wywołuje funkcję z argumentami 5 i 3, a zwróconą wartość (8) zapisuje w 'sum_value'
print(sum_value)      # Wypisuje wartość zmiennej 'sum_value' w konsoli