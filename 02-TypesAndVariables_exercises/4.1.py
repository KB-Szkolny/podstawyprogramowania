name = "Adam"       # Przypisuje imię (str)
age = 20             # Przypisuje wiek (int)
height = 180        # Przypisuje wzrost w cm (int)

print(f"My name is {name}.")        # Wypisuje imię z użyciem f-stringa
print(f"I am {age} years old, and my height is {height} cm.") # Wypisuje wiek i wzrost 
print(f"In 6 years I will be {age + 6} years old.")   # Wykonuje działanie wewnątrz f-stringa