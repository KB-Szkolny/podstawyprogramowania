print(f'a : {ord("a")}')  # Kody dla małych liter
print(f'b : {ord("b")}')
print(f'z : {ord("z")}')

print(f'A : {ord("A")}')  # Kody dla wielkich liter
print(f'B : {ord("B")}')
print(f'Z : {ord("Z")}')

print(f'1 : {ord("1")}')  # Kod dla cyfry

print(f'= : {ord("=")}')  # Kody dla symboli
print(f'+ : {ord("+")}')
print(f'€ : {ord("€")}')  # Kod dla znaku waluty Euro (Unicode)