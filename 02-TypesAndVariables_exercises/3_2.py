number1 = 71     # Pierwsza liczba (int)
number2 = 14     # Druga liczba (int)
number3 = 50     # Trzecia liczba (int)

result = number1 + number2 + number3  # Oblicza sumę trzech liczb (71 + 14 + 50 = 135)

print('Number 1: ', number1)     # Wypisuje wartość zmiennej number1
print('Number 2: ', number2)      # Wypisuje wartość zmiennej number2
print('Number 3: ', number3)    # Wypisuje wartość zmiennej number3
print('The result of summation: ', result)  # Wypisuje obliczoną sumę