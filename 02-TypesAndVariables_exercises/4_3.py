a = 3          # Pierwsza liczba (int)
b = 5          # Druga liczba (int)

print(f'{a}+{b} = {a + b}')            # Dodawanie w f-stringu
print(f'{a}-{b} = {a - b}')            # Odejmowanie w f-stringu
print(f'{a}*{b} = {a * b}')            # Mnożenie w f-stringu
print(f'{a}/{b} = {a / b}')            # Dzielenie w f-stringu 